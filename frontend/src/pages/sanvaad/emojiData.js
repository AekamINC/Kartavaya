/**
 * emojiData.js — the picker's vocabulary. LAZILY LOADED; never import this
 * statically.
 *
 * `docs/proposals/09-sanvaad-design-system.html` §4 settles four things about
 * the picker and three of them are decisions about this file:
 *
 *  · NATIVE EMOJI, NO IMAGE SPRITES. "Every target platform renders them. A
 *    sprite sheet is ~400 KB and a licence question for nothing." So the data
 *    here is characters and words, and the font does the drawing.
 *  · SEARCH IS KEYWORD, NOT FUZZY. Every entry carries a space-separated
 *    keyword string and the search is a substring test over it. Fuzzy matching
 *    on a list this size returns 😴 for "sad" and teaches people to scroll
 *    instead of type.
 *  · IT MUST NOT SIT IN THE MAIN BUNDLE. `EmojiPicker.jsx` reaches this through
 *    `import('./emojiData')`, which Vite emits as its own chunk, so the cost is
 *    paid by the first reader who opens the picker and by nobody else. A static
 *    import anywhere — including from a test — puts it back in the entry chunk
 *    and silently undoes that. `sanvaadEmoji.test.js` imports it dynamically for
 *    the same reason.
 *  · THE EXISTING ENDPOINT IS UNCHANGED. `samvada_message_reactions.emoji` is
 *    already free text, so nothing here needs a migration.
 *
 * HOW LONG THIS LIST IS, HONESTLY. Proposal 09 costs the picker against "a
 * curated ~1,500-emoji list with keywords". This is ~460, hand-authored, and the
 * shortfall is deliberate rather than unfinished: the missing thousand are
 * overwhelmingly flags, skin-tone and gender variants of entries already here,
 * and the long tail of Unicode that a chartered-accountancy firm's channel will
 * never reach for. Every one of them is still POSTABLE — the composer takes any
 * character the reader's own OS keyboard emits, and the reaction column is free
 * text — they are simply not offered in the grid. If the tail is ever wanted,
 * this file grows and nothing else changes.
 *
 * KEYWORDS ARE BRITISH AND AMERICAN WHERE THEY DIVERGE ('colour color'), and
 * they include the Indian-English word where one exists ('rupee', 'namaste',
 * 'diya'), because the people typing into this box are in India and 'lakh' is
 * not a synonym anybody has to be taught.
 *
 * The name is duplicated into the keyword string on purpose, so a caller can
 * match on `keywords` alone and never has to concatenate two fields.
 */

