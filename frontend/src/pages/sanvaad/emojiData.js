/**
 * Every entry, flattened, with its category id — the shape search wants.
 *
 * Built once at module evaluation, which happens inside the lazy chunk, so it
 * costs nothing until the picker is opened for the first time in a session.
 */
export const ALL = CATEGORIES.flatMap(c =>
  c.emoji.map(([char, keywords]) => ({ char, keywords, cat: c.id }))
);

/**
 * Substring over the keyword string, in declaration order, capped.
 *
 * NOT fuzzy and not scored, per proposal 09. A substring test means "thu" finds
 * 👍 (thumbs) and 🌩 (thunderstorm) and nothing else, which is a rule a reader
 * can hold in their head; a fuzzy matcher would also return 😴 for "sad" and the
 * only way to find anything after that is to scroll.
 *
 * The cap is the one concession to the grid: past ~120 hits the results stop
 * being a list and start being the whole dataset in a different order, and a
 * query that vague is better narrowed than paged.
 */
export function searchEmoji(query, limit = 120) {
  const q = String(query || '').trim().toLowerCase();
  if (!q) return [];
  const out = [];
  for (const e of ALL) {
    if (e.keywords.includes(q)) {
      out.push(e);
      if (out.length >= limit) break;
    }
  }
  return out;
}
